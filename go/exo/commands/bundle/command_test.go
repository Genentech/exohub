func TestLoadPresetIncrementalField(t *testing.T) {
	dir := t.TempDir()
	origDir, _ := os.Getwd()
	os.Chdir(dir)
	defer os.Chdir(origDir)

	os.MkdirAll(".exohub", 0755)
	content := `presets:
  - name: default
    scope: all
    incremental: true
  - name: no-incremental
    scope: all
`
	os.WriteFile(filepath.Join(".exohub", "bundle"), []byte(content), 0644)

	// Preset with incremental: true should parse correctly
	preset, err := loadPreset("default")
	if err != nil {
		t.Fatalf("loadPreset(default) error: %v", err)
	}
	if !preset.Incremental {
		t.Errorf("expected preset.Incremental = true, got false")
	}

	// Preset without incremental field should default to false
	preset, err = loadPreset("no-incremental")
	if err != nil {
		t.Fatalf("loadPreset(no-incremental) error: %v", err)
	}
	if preset.Incremental {
		t.Errorf("expected preset.Incremental = false, got true")
	}

	// CLI flag false + preset true => incremental should be true (OR logic)
	incremental := false || preset.Incremental
	if incremental {
		t.Errorf("expected merged incremental = false when both are false")
	}

	preset, _ = loadPreset("default")
	incremental = false || preset.Incremental
	if !incremental {
		t.Errorf("expected merged incremental = true when preset.Incremental = true and CLI flag = false")
	}

	// CLI flag true overrides everything
	incremental = true || preset.Incremental
	if !incremental {
		t.Errorf("expected merged incremental = true when CLI flag = true")
	}
}

func TestExpandCommits(t *testing.T) {
	commitMap := map[string]Commit{
		"aaa": {Hash: "aaa", Subject: "first", CommitterDate: "2024-01-01T00:00:00Z"},
		"bbb": {Hash: "bbb", Subject: "second", CommitterDate: "2024-01-02T00:00:00Z"},
		"ccc": {Hash: "ccc", Subject: "third", CommitterDate: "2024-01-03T00:00:00Z"},
	}

	// Normal expansion
	result := expandCommits([]string{"bbb", "aaa"}, commitMap)
	if len(result) != 2 {
		t.Fatalf("expected 2 commits, got %d", len(result))
	}
	// Should be sorted by date descending
	if result[0].Hash != "bbb" {
		t.Errorf("first commit should be bbb (most recent), got %s", result[0].Hash)
	}

	// Deduplication
	result = expandCommits([]string{"aaa", "aaa", "aaa"}, commitMap)
	if len(result) != 1 {
		t.Errorf("expected 1 commit after dedup, got %d", len(result))
	}

	// Empty hashes
	result = expandCommits(nil, commitMap)
	if len(result) != 0 {
		t.Errorf("expected 0 commits for nil input, got %d", len(result))
	}

	// Hash not in map
	result = expandCommits([]string{"zzz"}, commitMap)
	if len(result) != 0 {
		t.Errorf("expected 0 commits for unknown hash, got %d", len(result))
	}
}

