func TestParseMarkdown(t *testing.T) {
	t.Run("title and sections", func(t *testing.T) {
		source := []byte("# My Dataset\n\n## Installation\n\nSome text.\n\n### Usage\n\nMore text.\n")
		title, sections, content, metadata := parseMarkdown(source)
		if title != "My Dataset" {
			t.Errorf("title = %q, want %q", title, "My Dataset")
		}
		if len(sections) != 3 {
			t.Fatalf("expected 3 sections, got %d", len(sections))
		}
		if sections[0].Level != 1 || sections[0].Text != "My Dataset" {
			t.Errorf("sections[0] = %+v", sections[0])
		}
		if sections[1].Level != 2 || sections[1].Text != "Installation" {
			t.Errorf("sections[1] = %+v", sections[1])
		}
		if sections[2].Level != 3 || sections[2].Text != "Usage" {
			t.Errorf("sections[2] = %+v", sections[2])
		}
		if content == "" {
			t.Error("content should not be empty")
		}
		if len(metadata) != 0 {
			t.Errorf("metadata should be empty, got %v", metadata)
		}
	})

	t.Run("no headings", func(t *testing.T) {
		source := []byte("Just some plain text without any headings.\n")
		title, sections, content, _ := parseMarkdown(source)
		if title != "" {
			t.Errorf("title = %q, want empty", title)
		}
		if len(sections) != 0 {
			t.Errorf("expected 0 sections, got %d", len(sections))
		}
		if content == "" {
			t.Error("content should not be empty")
		}
	})

	t.Run("front matter populates metadata", func(t *testing.T) {
		source := []byte("---\ntag:\n  - rnaseq\n  - bulk\nspecies: human\n---\n# My Dataset\n\nContent here.\n")
		title, _, content, metadata := parseMarkdown(source)
		if title != "My Dataset" {
			t.Errorf("title = %q, want %q", title, "My Dataset")
		}
		tags, ok := metadata["tag"]
		if !ok || len(tags) != 2 || tags[0] != "rnaseq" || tags[1] != "bulk" {
			t.Errorf("metadata[tag] = %v, want [rnaseq bulk]", tags)
		}
		species, ok := metadata["species"]
		if !ok || len(species) != 1 || species[0] != "human" {
			t.Errorf("metadata[species] = %v, want [human]", species)
		}
		// Front matter should be stripped from content
		if strings.Contains(content, "---") {
			t.Error("content should not contain front matter delimiters")
		}
		if !strings.Contains(content, "# My Dataset") {
			t.Error("content should contain the markdown body")
		}
	})

	t.Run("no front matter", func(t *testing.T) {
		source := []byte("# Title\n\nBody text.\n")
		_, _, _, metadata := parseMarkdown(source)
		if len(metadata) != 0 {
			t.Errorf("metadata should be empty, got %v", metadata)
		}
	})
}

