func TestDeriveChunks(t *testing.T) {
	key := "SHA256E-s2684354560--abc123def456.parquet"
	fileSize := int64(2684354560)  // ~2.5 GiB
	chunkSize := int64(1073741824) // 1 GiB
	s3URL := "s3://bucket/prefix"

	chunks := deriveChunks(key, fileSize, chunkSize, s3URL)

	if len(chunks) != 3 {
		t.Fatalf("expected 3 chunks, got %d", len(chunks))
	}

	// Chunk 1
	if chunks[0].ChunkNumber != 1 {
		t.Errorf("chunk 1 number = %d, want 1", chunks[0].ChunkNumber)
	}
	if chunks[0].ChunkSize != chunkSize {
		t.Errorf("chunk 1 size = %d, want %d", chunks[0].ChunkSize, chunkSize)
	}
	expectedKey1 := "SHA256E-s2684354560-S1073741824-C1--abc123def456.parquet"
	if chunks[0].ChunkKey != expectedKey1 {
		t.Errorf("chunk 1 key = %q, want %q", chunks[0].ChunkKey, expectedKey1)
	}
	if chunks[0].S3Path != s3URL+"/"+expectedKey1 {
		t.Errorf("chunk 1 s3path = %q, want %q", chunks[0].S3Path, s3URL+"/"+expectedKey1)
	}

	// Chunk 3 (last, partial)
	if chunks[2].ChunkNumber != 3 {
		t.Errorf("chunk 3 number = %d, want 3", chunks[2].ChunkNumber)
	}
	expectedLastSize := fileSize - 2*chunkSize
	if chunks[2].ChunkSize != expectedLastSize {
		t.Errorf("chunk 3 size = %d, want %d", chunks[2].ChunkSize, expectedLastSize)
	}
}

func TestDeriveChunksNoSplit(t *testing.T) {
	key := "SHA256E-s100--abc.dat"
	// Key without -- separator should return nil
	chunks := deriveChunks("NODASH", 100, 50, "s3://b")
	if chunks != nil {
		t.Errorf("expected nil chunks for key without --, got %v", chunks)
	}

	// File smaller than chunk size: no chunks should be generated by caller,
	// but deriveChunks still produces 1 chunk if called
	chunks = deriveChunks(key, 50, 100, "s3://b")
	if len(chunks) != 1 {
		t.Errorf("expected 1 chunk for small file, got %d", len(chunks))
	}
}

