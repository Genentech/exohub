func TestShouldSkipPath(t *testing.T) {
	tests := []struct {
		name       string
		path       string
		preset     Preset
		wantSkip   bool
		wantReason bool // whether a non-empty reason is expected
	}{
		{
			name:     "normal file not skipped",
			path:     "data/file.parquet",
			preset:   Preset{},
			wantSkip: false,
		},
		{
			name:     "exohub always skipped",
			path:     ".exohub/bundle",
			preset:   Preset{IncludeHidden: true},
			wantSkip: true,
		},
		{
			name:       "artifactdb skipped by default",
			path:       ".artifactdb/metadata.json",
			preset:     Preset{},
			wantSkip:   true,
			wantReason: true,
		},
		{
			name:       "artifactdb skipped even with include_hidden",
			path:       ".artifactdb/index.json",
			preset:     Preset{IncludeHidden: true},
			wantSkip:   true,
			wantReason: true,
		},
		{
			name:     "artifactdb included via explicit include pattern",
			path:     ".artifactdb/metadata.json",
			preset:   Preset{Include: []string{".artifactdb/**"}},
			wantSkip: false,
		},
		{
			name:     "hidden path skipped by default",
			path:     ".github/workflows/ci.yml",
			preset:   Preset{},
			wantSkip: true,
		},
		{
			name:     "hidden path included with include_hidden",
			path:     ".github/workflows/ci.yml",
			preset:   Preset{IncludeHidden: true},
			wantSkip: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			skip, reason := shouldSkipPath(tt.path, tt.preset)
			if skip != tt.wantSkip {
				t.Errorf("shouldSkipPath(%q) skip = %v, want %v", tt.path, skip, tt.wantSkip)
			}
			if tt.wantReason && reason == "" {
				t.Errorf("shouldSkipPath(%q) expected non-empty reason", tt.path)
			}
			if !tt.wantReason && reason != "" {
				t.Errorf("shouldSkipPath(%q) unexpected reason: %s", tt.path, reason)
			}
		})
	}
}

