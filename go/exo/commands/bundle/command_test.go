func TestCheckCommitReachabilityDiverged(t *testing.T) {
	originDir := t.TempDir()
	local1Dir := t.TempDir()
	local2Dir := t.TempDir()
	env := append(os.Environ(), "GIT_CONFIG_NOSYSTEM=1", "HOME="+local1Dir)

	runIn := func(dir string, args ...string) {
		t.Helper()
		cmd := exec.Command(args[0], args[1:]...)
		cmd.Dir = dir
		cmd.Env = env
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("command %v in %s failed: %v\n%s", args, dir, err, out)
		}
	}

	// Create bare origin and initial clone
	runIn(originDir, "git", "init", "--bare")
	runIn(local1Dir, "git", "clone", originDir, ".")
	runIn(local1Dir, "git", "config", "user.email", "test@test.com")
	runIn(local1Dir, "git", "config", "user.name", "Test")
	os.WriteFile(filepath.Join(local1Dir, "file.txt"), []byte("initial\n"), 0o644)
	runIn(local1Dir, "git", "add", ".")
	runIn(local1Dir, "git", "commit", "-m", "initial")
	runIn(local1Dir, "git", "push")

	// Second clone makes a different commit and force-pushes
	runIn(local2Dir, "git", "clone", originDir, ".")
	runIn(local2Dir, "git", "config", "user.email", "test@test.com")
	runIn(local2Dir, "git", "config", "user.name", "Test")
	os.WriteFile(filepath.Join(local2Dir, "file.txt"), []byte("divergent\n"), 0o644)
	runIn(local2Dir, "git", "add", ".")
	runIn(local2Dir, "git", "commit", "-m", "divergent change")
	runIn(local2Dir, "git", "push", "--force")

	// Back in local1: add a local commit (now diverged from origin)
	os.WriteFile(filepath.Join(local1Dir, "other.txt"), []byte("local\n"), 0o644)
	runIn(local1Dir, "git", "add", ".")
	runIn(local1Dir, "git", "commit", "-m", "local change")
	runIn(local1Dir, "git", "fetch")

	origDir, _ := os.Getwd()
	os.Chdir(local1Dir)
	defer os.Chdir(origDir)

	cmd := exec.Command("git", "rev-parse", "HEAD")
	cmd.Dir = local1Dir
	out, _ := cmd.Output()
	headHash := strings.TrimSpace(string(out))

	result := checkCommitReachability(headHash)
	if result == nil {
		t.Fatal("expected non-nil result for diverged repo")
	}
	if !result.Diverged {
		t.Error("expected Diverged=true")
	}
	if result.LocalOnly != 1 {
		t.Errorf("expected LocalOnly=1, got %d", result.LocalOnly)
	}
	if result.RemoteOnly != 1 {
		t.Errorf("expected RemoteOnly=1, got %d", result.RemoteOnly)
	}
}
