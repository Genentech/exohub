func TestBuildLocations(t *testing.T) {
	remoteConfigs := map[string]RemoteConfig{
		"s3-annex": {
			Name:  "s3-annex",
			Type:  "annex",
			S3URL: "s3://bucket/prefix",
			Chunk: "1GiB",
		},
		"s3-export": {
			Name:  "s3-export",
			Type:  "export",
			S3URL: "s3://bucket/export",
		},
	}

	whereis := annexWhereisEntry{
		File: "data/file.parquet",
		Key:  "SHA256E-s100--abc123.parquet",
		Whereis: []annexWhereisRemote{
			{UUID: "uuid-1", Description: "uuid-1 -- s3-annex [origin]", Here: false},
			{UUID: "uuid-local", Description: "uuid-local -- here", Here: true},
			{UUID: "uuid-2", Description: "uuid-2 -- s3-export", Here: false},
		},
	}

	locations := buildLocations("data/file.parquet", "SHA256E-s100--abc123.parquet", 100, whereis, remoteConfigs)

	// Should have 2 locations (local excluded)
	if len(locations) != 2 {
		t.Fatalf("expected 2 locations, got %d", len(locations))
	}

	// Annex remote
	if locations[0].Remote != "s3-annex" {
		t.Errorf("location 0 remote = %q, want s3-annex", locations[0].Remote)
	}
	if locations[0].Type != "annex" {
		t.Errorf("location 0 type = %q, want annex", locations[0].Type)
	}
	// Small file (100 bytes < 1GiB) with chunking enabled: git-annex still uses chunk key format
	if locations[0].S3Object != "" {
		t.Errorf("chunked file should have empty s3_object, got %q", locations[0].S3Object)
	}
	if len(locations[0].Chunks) != 1 {
		t.Fatalf("expected 1 chunk for small file with chunking enabled, got %d", len(locations[0].Chunks))
	}
	expectedChunkKey := "SHA256E-s100-S1073741824-C1--abc123.parquet"
	if locations[0].Chunks[0].ChunkKey != expectedChunkKey {
		t.Errorf("chunk key = %q, want %q", locations[0].Chunks[0].ChunkKey, expectedChunkKey)
	}
	if locations[0].Chunks[0].ChunkSize != 100 {
		t.Errorf("chunk size = %d, want 100", locations[0].Chunks[0].ChunkSize)
	}

	// Export remote
	if locations[1].Remote != "s3-export" {
		t.Errorf("location 1 remote = %q, want s3-export", locations[1].Remote)
	}
	if locations[1].ExportPath != "s3://bucket/export/data/file.parquet" {
		t.Errorf("location 1 export_path = %q", locations[1].ExportPath)
	}
}

