type addOptions struct {
	generated     []string
	used          []string
	derivedFrom   []string
	noDerivedFrom bool
	revisionOf    []string
	plan          string
	agent         string
	onBehalfOf    string
	model         string
	started       string
	ended         string
	assertion     string
	evidence      string
	supersedes    []string
	skipExisting  bool
	dryRun        bool
	jsonOutput    bool
}

// newAddCommand returns `exo provenance add` (design D6).
func newAddCommand() *cobra.Command {
	var opts addOptions

	cmd := &cobra.Command{
		Use:   "add",
		Short: "Create a new provenance record",
		Long: `Create one provenance record from flags and write it as a new file
under .exohub/provenance/.

Paths are resolved to content identifiers from the index: an annex key for
annexed files, a git blob id for git files, or a git tree id for a folder
path ending in "/" (a folder collection). Untracked paths, and paths whose
worktree content differs from the index, are rejected with a hint to run
'exo add' first; for a folder, every file under it must be tracked and
unchanged. Nothing is written on rejection.

--revision-of links a generated entity to a previous version with
wasRevisionOf: an IRI is taken as-is, '<ref>:<path>' resolves path at that
ref (a folder's previous tree id, for example), and a plain path resolves
from the index like the other flags. A --revision-of value that resolves to
the same id as a --generated entity is rejected: an entity cannot be a
revision of itself, and an unchanged path usually means '<ref>:<path>' was
meant instead.

The person agent defaults to the exo login identity (preferred_username as
the identifier, the token's full name as a label). Without a login token,
pass --agent person:<unix id>. An AI agent or tool identifies itself with
--agent software:<name>, optionally --model and --on-behalf-of
person:<unix id>.

This command never modifies an existing record file; a correction is a new
record with --supersedes.

Before writing, each --generated entity is checked against existing
provenance (worktree records, including untracked ones): if a
non-superseded record already states wasGeneratedBy for it, add fails and
writes nothing, naming the conflicting record. Pass --supersedes with that
record's id to replace it (the correction workflow), or --skip-existing to
drop already-covered --generated entries and write a record for the rest —
if every entity is already covered, --skip-existing writes nothing and
exits 0, so a generation loop can be re-run safely.`,
		SilenceUsage: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			return runAdd(cmd, opts)
		},
	}

	flags := cmd.Flags()
	flags.StringArrayVar(&opts.generated, "generated", nil, "path generated by this activity (repeatable); a folder path must end in \"/\"")
	flags.StringArrayVar(&opts.used, "used", nil, "path or IRI used as input by this activity (repeatable)")
	flags.StringArrayVar(&opts.derivedFrom, "derived-from", nil, "path or IRI the generated entities were derived from (repeatable); defaults to --used")
	flags.BoolVar(&opts.noDerivedFrom, "no-derived-from", false, "do not record a wasDerivedFrom relationship")
	flags.StringArrayVar(&opts.revisionOf, "revision-of", nil, "path, IRI, or <ref>:<path>, this generated entity is a revision of (repeatable)")
	flags.StringVar(&opts.plan, "plan", "", "path or IRI of the plan (script, workflow) that was run (hadPlan)")
	flags.StringVar(&opts.agent, "agent", "", "person:<unix id> or software:<name> asserting this record; defaults to the exo login identity")
	flags.StringVar(&opts.onBehalfOf, "on-behalf-of", "", "person:<unix id> the software agent acted on behalf of")
	flags.StringVar(&opts.model, "model", "", "model identifier for a software agent (exo:model)")
	flags.StringVar(&opts.started, "started", "", "activity start time (RFC3339)")
	flags.StringVar(&opts.ended, "ended", "", "activity end time (RFC3339)")
	flags.StringVar(&opts.assertion, "assertion", string(lib.AssertionAsserted), "recorded, imported or asserted")
	flags.StringVar(&opts.evidence, "evidence", "", "evidence for an inferred claim (exo:evidence)")
	flags.StringArrayVar(&opts.supersedes, "supersedes", nil, "record id this record supersedes (repeatable)")
	flags.BoolVar(&opts.skipExisting, "skip-existing", false, "drop --generated entries that already have provenance instead of failing; exit 0 and write nothing if none remain")
	flags.BoolVar(&opts.dryRun, "dry-run", false, "print the record that would be written; write and stage nothing")
	flags.BoolVar(&opts.jsonOutput, "json", false, "emit machine-readable JSON")

	return cmd
}

func runAdd(cmd *cobra.Command, opts addOptions) error {
	if len(opts.generated) == 0 {
		return fmt.Errorf("--generated is required (repeatable)")
	}

	assertion := lib.Assertion(opts.assertion)
	switch assertion {
	case lib.AssertionRecorded, lib.AssertionImported, lib.AssertionAsserted:
	default:
		return fmt.Errorf("--assertion must be recorded, imported or asserted, got %q", opts.assertion)
	}

	if opts.noDerivedFrom && len(opts.derivedFrom) > 0 {
		return fmt.Errorf("--derived-from and --no-derived-from are mutually exclusive")
	}

	if opts.started != "" {
		if _, err := time.Parse(time.RFC3339, opts.started); err != nil {
			return fmt.Errorf("--started must be RFC3339, got %q: %w", opts.started, err)
		}
	}
	if opts.ended != "" {
		if _, err := time.Parse(time.RFC3339, opts.ended); err != nil {
			return fmt.Errorf("--ended must be RFC3339, got %q: %w", opts.ended, err)
		}
	}
	for _, id := range opts.supersedes {
		if !lib.IsUUIDv7(id) {
			return fmt.Errorf("--supersedes must be urn:exohub:record:<UUIDv7>, got %q", id)
		}
	}
	if opts.model != "" {
		ref, err := parseAgentRefIfSet(opts.agent)
		if err != nil {
			return err
		}
		if ref == nil || ref.kind != "software" {
			return fmt.Errorf("--model requires --agent software:<name>")
		}
	}

	root, err := repoRoot()
	if err != nil {
		return err
	}
	reader := lib.NewWorktreeReader(root)

	graph := map[string]lib.Node{}

	generatedIDs, err := resolveEntities(root, reader, graph, opts.generated)
	if err != nil {
		return err
	}

	generatedPaths, generatedIDs, err := rejectDuplicateGeneration(cmd, root, opts, graph, opts.generated, generatedIDs)
	if err != nil {
		return err
	}
	if len(generatedPaths) == 0 {
		fmt.Fprintln(cmd.OutOrStdout(), "Nothing to do: every --generated entity already has provenance")
		return nil
	}
	opts.generated = generatedPaths

	usedIDs, err := resolveEntities(root, reader, graph, opts.used)
	if err != nil {
		return err
	}

	var derivedFromIDs []string
	switch {
	case opts.noDerivedFrom:
		// no wasDerivedFrom statement.
	case len(opts.derivedFrom) > 0:
		derivedFromIDs, err = resolveEntities(root, reader, graph, opts.derivedFrom)
		if err != nil {
			return err
		}
	default:
		derivedFromIDs = usedIDs
	}

	revisionOfIDs, err := resolveRevisionOfEntities(root, reader, graph, generatedIDs, opts.revisionOf)
	if err != nil {
		return err
	}

	var planID string
	if opts.plan != "" {
		ids, err := resolveEntities(root, reader, graph, []string{opts.plan})
		if err != nil {
			return err
		}
		planID = ids[0]
	}

	personID, personLabel, assertedByID, err := resolveAgents(opts)
	if err != nil {
		return err
	}

	if personID != "" {
		person := lib.Node{"@id": personID, "@type": "Person"}
		if personLabel != "" {
			person["label"] = personLabel
		}
		graph[personID] = person
	}

	// The Activity's wasAssociatedWith names the agents that carried out the
	// activity (PROV), not just the one that asserted the record: a software
	// agent and the person it acted for are both associated, software agent
	// first for a deterministic order (design D6, D11).
	var associatedIDs []string
	if opts.agent != "" {
		ref, err := parseAgentRef(opts.agent)
		if err != nil {
			return err
		}
		if ref.kind == "software" {
			sw := lib.Node{"@id": ref.entityID(), "@type": "SoftwareAgent"}
			if opts.model != "" {
				sw["exo:model"] = opts.model
			}
			if personID != "" {
				sw["actedOnBehalfOf"] = personID
			}
			graph[ref.entityID()] = sw
			associatedIDs = append(associatedIDs, ref.entityID())
		}
	}
	if personID != "" {
		associatedIDs = append(associatedIDs, personID)
	}
	if len(associatedIDs) == 0 && assertedByID != "" {
		associatedIDs = append(associatedIDs, assertedByID)
	}

	activityID := lib.NewActivityID()
	activity := lib.Node{"@id": activityID, "@type": "Activity"}
	if len(usedIDs) > 0 {
		activity["used"] = toValue(usedIDs)
	}
	if planID != "" {
		activity["hadPlan"] = planID
	}
	if len(associatedIDs) > 0 {
		activity["wasAssociatedWith"] = toValue(associatedIDs)
	}
	if opts.started != "" {
		activity["startedAtTime"] = opts.started
	}
	if opts.ended != "" {
		activity["endedAtTime"] = opts.ended
	}
	graph[activityID] = activity

	for _, id := range generatedIDs {
		n := graph[id]
		if n == nil {
			n = lib.Node{"@id": id, "@type": "Entity"}
		}
		n["wasGeneratedBy"] = activityID
		if len(derivedFromIDs) > 0 {
			n["wasDerivedFrom"] = toValue(derivedFromIDs)
		}
		if len(revisionOfIDs) > 0 {
			n["wasRevisionOf"] = toValue(revisionOfIDs)
		}
		graph[id] = n
	}

	generatedAt := time.Now().UTC()
	rec := &lib.Record{
		Context:         lib.ContextIRI,
		ID:              lib.NewRecordID(),
		Assertion:       assertion,
		AssertedBy:      assertedByID,
		GeneratedAtTime: generatedAt.Format(time.RFC3339),
		Evidence:        opts.evidence,
		Supersedes:      append([]string(nil), opts.supersedes...),
		Graph:           graphNodes(graph),
	}

	data, err := lib.Serialize(rec)
	if err != nil {
		return fmt.Errorf("build record: %w", err)
	}
	if _, err := lib.Parse(data); err != nil {
		return fmt.Errorf("built an invalid record: %w", err)
	}

	if opts.dryRun {
		fmt.Fprintln(cmd.OutOrStdout(), string(data))
		return nil
	}

	slug := recordSlug(opts.generated[0])
	path, err := lib.RecordPath(generatedAt, slug, rec.ID)
	if err != nil {
		return fmt.Errorf("build record path: %w", err)
	}

	if err := writeRecordFile(root, path, data); err != nil {
		return err
	}
	if err := stageRecord(root, path); err != nil {
		return err
	}

	if opts.jsonOutput {
		out := struct {
			Path   string          `json:"path"`
			Record json.RawMessage `json:"record"`
		}{Path: path, Record: data}
		enc, err := json.MarshalIndent(out, "", "  ")
		if err != nil {
			return fmt.Errorf("encode result: %w", err)
		}
		fmt.Fprintln(cmd.OutOrStdout(), string(enc))
	} else {
		fmt.Fprintf(cmd.OutOrStdout(), "Wrote and staged %s\n", path)
	}
	return nil
}

// agentRef is a parsed --agent, --on-behalf-of or similar reference of the
// form "person:<unix id>" or "software:<name>" (design D6).
type agentRef struct {
	kind string
	id   string
}

func parseAgentRef(s string) (agentRef, error) {
	kind, id, found := strings.Cut(s, ":")
	if !found || id == "" {
		return agentRef{}, fmt.Errorf("invalid agent %q, want person:<unix id> or software:<name>", s)
	}
	switch kind {
	case "person", "software":
	default:
		return agentRef{}, fmt.Errorf("invalid agent kind %q in %q, want person:<unix id> or software:<name>", kind, s)
	}
	if !lib.ValidAgentName(id) {
		return agentRef{}, fmt.Errorf("invalid agent name %q in %q: names must be non-empty and contain no whitespace or \"/\"", id, s)
	}
	return agentRef{kind: kind, id: id}, nil
}

func (a agentRef) entityID() string {
	if a.kind == "person" {
		return lib.PersonAgentID(a.id)
	}
	return lib.SoftwareAgentID(a.id)
}

// resolveAgents resolves --agent and --on-behalf-of into the person
// identity (if any, for the Activity's wasAssociatedWith and Person node),
// its label (from the login token, if that is the source), and the id that
// exo:assertedBy must reference (design D5, D6, D11).
func resolveAgents(opts addOptions) (personID, personLabel, assertedByID string, err error) {
	var ref agentRef
	explicit := opts.agent != ""
	if explicit {
		ref, err = parseAgentRef(opts.agent)
		if err != nil {
			return "", "", "", err
		}
	}

	switch {
	case explicit && ref.kind == "person":
		personID = ref.entityID()
		assertedByID = personID
	case explicit && ref.kind == "software":
		assertedByID = ref.entityID()
		switch {
		case opts.onBehalfOf != "":
			onBehalf, err := parseAgentRef(opts.onBehalfOf)
			if err != nil {
				return "", "", "", err
			}
			if onBehalf.kind != "person" {
				return "", "", "", fmt.Errorf("--on-behalf-of must be person:<unix id>, got %q", opts.onBehalfOf)
			}
			personID = onBehalf.entityID()
		default:
			// D11: a software agent acts on behalf of the user; default to the
			// login identity when no --on-behalf-of is given and a token is
			// available. Without a token, keep the pre-review behaviour: no
			// associated person.
			if unixID, label, ok := loginPersonIdentity(); ok {
				personID = lib.PersonAgentID(unixID)
				personLabel = label
			}
		}
	default:
		unixID, label, ok := loginPersonIdentity()
		if !ok {
			return "", "", "", fmt.Errorf("no exo login token found; run \"exo login\" or pass --agent person:<unix id>")
		}
		personID = lib.PersonAgentID(unixID)
		personLabel = label
		assertedByID = personID
	}

	if (!explicit || ref.kind != "software") && opts.onBehalfOf != "" {
		return "", "", "", fmt.Errorf("--on-behalf-of requires --agent software:<name>")
	}

	return personID, personLabel, assertedByID, nil
}

// parseAgentRefIfSet parses s as an agentRef if it is non-empty, returning
// nil if s is empty (used to validate --model against --agent before the
// rest of the command runs).
func parseAgentRefIfSet(s string) (*agentRef, error) {
	if s == "" {
		return nil, nil
	}
	ref, err := parseAgentRef(s)
	if err != nil {
		return nil, err
	}
	return &ref, nil
}

// loginPersonIdentity returns the person identity from the stored exo login
// token (design D5), or ok=false if no usable token is available.
func loginPersonIdentity() (unixID, label string, ok bool) {
	tokenFile, err := login.GetTokenFile()
	if err != nil {
		return "", "", false
	}
	token, err := login.LoadToken(tokenFile)
	if err != nil || token.AccessToken == "" {
		return "", "", false
	}
	return auth.PersonIdentityFromToken(token.AccessToken)
}

// looksLikeIRI reports whether s should be treated as an external
// identifier (a URL or urn:, design D5) rather than a repository path.
func looksLikeIRI(s string) bool {
	return strings.Contains(s, "://") || strings.HasPrefix(s, "urn:")
}

// generationConflict is one existing, non-superseded record that already
// states wasGeneratedBy for a --generated id.
type generationConflict struct {
	recordID string // the conflicting record's @id.
	path     string // the conflicting record's file path.
}

// rejectDuplicateGeneration checks generatedIDs (parallel to
// generatedPaths, both as resolved by resolveEntities for --generated)
// against existing provenance before anything is written (design D15
// "add", issue: re-running `add --generated X` must not write a record
// that conflicts with an existing one). For each id already covered by a
// non-superseded record (and not named in --supersedes):
//   - without --skip-existing, the id blocks the command;
//   - with --skip-existing, the id (and its path and resolved graph node)
//     is dropped, with a note on stderr.
//
// It returns the surviving paths and ids in the original order. An empty
// result (with a nil error) means every --generated entity was already
// covered and --skip-existing was given: the caller writes nothing and
// exits 0.
func rejectDuplicateGeneration(cmd *cobra.Command, root string, opts addOptions, graph map[string]lib.Node, generatedPaths, generatedIDs []string) ([]string, []string, error) {
	conflicts, err := findGenerationConflicts(root, generatedIDs)
	if err != nil {
		return nil, nil, fmt.Errorf("check existing provenance: %w", err)
	}
	if len(conflicts) == 0 {
		return generatedPaths, generatedIDs, nil
	}

	superseded := make(map[string]bool, len(opts.supersedes))
	for _, id := range opts.supersedes {
		superseded[id] = true
	}

	var keptPaths, keptIDs []string
	var blocking []string
	for i, id := range generatedIDs {
		path := generatedPaths[i]
		var unresolved []generationConflict
		for _, c := range conflicts[id] {
			if !superseded[c.recordID] {
				unresolved = append(unresolved, c)
			}
		}
		if len(unresolved) == 0 {
			keptPaths = append(keptPaths, path)
			keptIDs = append(keptIDs, id)
			continue
		}
		if opts.skipExisting {
			delete(graph, id)
			c := unresolved[0]
			fmt.Fprintf(cmd.ErrOrStderr(), "skipping %s: already has provenance in %s (%s)\n", path, c.path, c.recordID)
			continue
		}
		blocking = append(blocking, duplicateGenerationMessage(path, unresolved[0]))
	}
	if len(blocking) > 0 {
		return nil, nil, fmt.Errorf("%s", strings.Join(blocking, "\n"))
	}
	return keptPaths, keptIDs, nil
}

// duplicateGenerationMessage formats the error for one --generated entity
// already covered by an existing record (issue: default behaviour is to
// error and write nothing, naming the conflicting record and both ways to
// proceed).
func duplicateGenerationMessage(path string, c generationConflict) string {
	return fmt.Sprintf(
		"%s already has provenance in %s (%s); nothing written. To replace it, rerun with --supersedes %s, or use --skip-existing.",
		path, c.path, c.recordID, c.recordID,
	)
}

// findGenerationConflicts returns, for each id in ids that an existing,
// non-superseded worktree record already states wasGeneratedBy for, every
// such record. It is a targeted lookup, not a full ListRecords read: one
// `git grep` to find candidate record files containing one of ids, parsed
// to confirm an actual wasGeneratedBy match, then one more `git grep` to
// find records that supersede a candidate (by its own @id), parsed to
// confirm (review/issue: "on 20,000 records this takes about 0.08s",
// "Same pattern as AllContentIDs in !256" — a constant number of git
// invocations regardless of repository size). It searches the worktree,
// including untracked files, matching the checked state `add` itself uses
// (design D15).
func findGenerationConflicts(root string, ids []string) (map[string][]generationConflict, error) {
	if len(ids) == 0 {
		return nil, nil
	}
	files, err := gitGrepRecordFiles(root, ids)
	if err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, nil
	}

	type candidate struct {
		path string
		rec  *lib.Record
	}
	candidates := make([]candidate, 0, len(files))
	for _, f := range files {
		data, err := os.ReadFile(filepath.Join(root, f))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", f, err)
		}
		rec, err := lib.Parse(data)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", f, err)
		}
		candidates = append(candidates, candidate{path: f, rec: rec})
	}

	candidateIDs := make([]string, len(candidates))
	for i, c := range candidates {
		candidateIDs[i] = c.rec.ID
	}
	supersedingFiles, err := gitGrepRecordFiles(root, candidateIDs)
	if err != nil {
		return nil, err
	}
	superseded := map[string]bool{}
	for _, f := range supersedingFiles {
		data, err := os.ReadFile(filepath.Join(root, f))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", f, err)
		}
		rec, err := lib.Parse(data)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", f, err)
		}
		for _, s := range rec.Supersedes {
			superseded[s] = true
		}
	}

	want := make(map[string]bool, len(ids))
	for _, id := range ids {
		want[id] = true
	}

	conflicts := map[string][]generationConflict{}
	for _, c := range candidates {
		if superseded[c.rec.ID] {
			continue
		}
		for _, n := range c.rec.Graph {
			nodeID := n.ID()
			if !want[nodeID] {
				continue
			}
			if _, ok := n["wasGeneratedBy"]; !ok {
				continue
			}
			conflicts[nodeID] = append(conflicts[nodeID], generationConflict{recordID: c.rec.ID, path: c.path})
		}
	}
	return conflicts, nil
}

// gitGrepRecordFiles returns the repo-root-relative paths of worktree
// files under lib.RecordDir (including untracked ones, --untracked) whose
// content contains at least one of needles (-F: literal, not regex),
// using one `git grep` invocation regardless of how many needles there
// are. A "no matches" exit (status 1) is not an error.
func gitGrepRecordFiles(root string, needles []string) ([]string, error) {
	if len(needles) == 0 {
		return nil, nil
	}
	args := []string{"--literal-pathspecs", "grep", "--untracked", "-F", "-l", "-z"}
	for _, n := range needles {
		args = append(args, "-e", n)
	}
	args = append(args, "--", lib.RecordDir+"/")
	cmd := exec.Command("git", args...)
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		if exitErr, ok := err.(*exec.ExitError); ok && exitErr.ExitCode() == 1 {
			return nil, nil
		}
		return nil, fmt.Errorf("git grep: %w", err)
	}
	trimmed := strings.TrimRight(string(out), "\x00")
	if trimmed == "" {
		return nil, nil
	}
	return strings.Split(trimmed, "\x00"), nil
}

func resolveEntities(root string, reader *lib.Reader, graph map[string]lib.Node, paths []string) ([]string, error) {
	ids := make([]string, 0, len(paths))
	for _, p := range paths {
		id, err := resolveEntity(root, reader, graph, p)
		if err != nil {
			return nil, err
		}
		ids = append(ids, id)
	}
	return ids, nil
}

// resolveEntity resolves one --generated/--used/--derived-from/--plan value
// to a content identifier: an external IRI is returned as-is; a repository
// path is normalized to repo-root-relative (so it resolves correctly when
// exo runs from a subdirectory), checked against the worktree, and resolved
// from the index (design D6, D13, D15).
func resolveEntity(root string, reader *lib.Reader, graph map[string]lib.Node, pathOrIRI string) (string, error) {
	if looksLikeIRI(pathOrIRI) {
		return pathOrIRI, nil
	}
	relPath, err := normalizeRepoPath(root, pathOrIRI)
	if err != nil {
		return "", err
	}
	if err := checkWorktreeClean(root, relPath); err != nil {
		return "", err
	}
	id, err := reader.ResolveContentID(relPath)
	if err != nil {
		if isUntrackedResolveError(err) {
			return "", fmt.Errorf("%s is untracked or does not exist; run \"exo add %s\" first", relPath, strings.TrimSuffix(relPath, "/"))
		}
		return "", fmt.Errorf("resolve %s: %w", relPath, err)
	}
	nodeType := "Entity"
	if strings.HasPrefix(id, lib.GitTreeURNPrefix) {
		nodeType = "Collection"
	}
	n := graph[id]
	if n == nil {
		n = lib.Node{"@id": id, "@type": nodeType}
	}
	n["exo:path"] = relPath
	graph[id] = n
	return id, nil
}

// revisionOfKind records how a --revision-of value was resolved, so
// resolveRevisionOfEntities can give a precise hint when it turns out to be
// the same entity as a --generated value.
type revisionOfKind int

const (
	revisionOfIRI revisionOfKind = iota
	revisionOfRef
	revisionOfPath
)

// resolveRevisionOfEntities resolves each --revision-of value to a content
// identifier and rejects one that resolves to the same id as a --generated
// entity: an entity cannot be a revision of itself (design D6, D13).
func resolveRevisionOfEntities(root string, reader *lib.Reader, graph map[string]lib.Node, generatedIDs []string, values []string) ([]string, error) {
	generated := make(map[string]bool, len(generatedIDs))
	for _, id := range generatedIDs {
		generated[id] = true
	}
	ids := make([]string, 0, len(values))
	for _, v := range values {
		id, kind, err := resolveRevisionOfValue(root, reader, graph, v)
		if err != nil {
			return nil, err
		}
		if generated[id] {
			if kind == revisionOfPath {
				return nil, fmt.Errorf("--revision-of %s resolves to the same id as a --generated value; an entity cannot be a revision of itself, and an unchanged path usually means you meant <ref>:%s for the previous version", v, v)
			}
			return nil, fmt.Errorf("--revision-of %s is the same entity as a --generated value; an entity cannot be a revision of itself", v)
		}
		ids = append(ids, id)
	}
	return ids, nil
}

// resolveRevisionOfValue resolves one --revision-of value: an IRI
// (urn:/scheme://) is taken as-is; a "<ref>:<path>" value, recognized by
// splitRefPath, resolves path in ref's tree via a lib.Reader in ModeRef
// (never checking worktree cleanliness, since the ref's content is
// historical, not the current worktree); any other value resolves from the
// index the same way as --generated/--used/--derived-from (design D6, D13).
func resolveRevisionOfValue(root string, reader *lib.Reader, graph map[string]lib.Node, value string) (id string, kind revisionOfKind, err error) {
	if looksLikeIRI(value) {
		id, err = resolveEntity(root, reader, graph, value)
		return id, revisionOfIRI, err
	}
	if ref, path, ok := splitRefPath(root, value); ok {
		id, err = resolveAtRef(root, graph, ref, path)
		return id, revisionOfRef, err
	}
	id, err = resolveEntity(root, reader, graph, value)
	return id, revisionOfPath, err
}

// splitRefPath splits value on its first ":" into a candidate ref and path,
// returning ok=false if value has no ":", either side is empty, or the
// candidate ref does not resolve to a commit with `git rev-parse --verify`.
// This keeps a plain path containing ":" working as a path (design D6's
// precedence: IRI, then "<ref>:<path>", then plain path). --end-of-options
// stops a ref value starting with "-" from being read as a git option
// (review of !260).
func splitRefPath(root, value string) (ref, path string, ok bool) {
	ref, path, found := strings.Cut(value, ":")
	if !found || ref == "" || path == "" {
		return "", "", false
	}
	cmd := exec.Command("git", "rev-parse", "--verify", "--quiet", "--end-of-options", ref+"^{commit}")
	cmd.Dir = root
	if err := cmd.Run(); err != nil {
		return "", "", false
	}
	return ref, path, true
}

// resolveAtRef resolves path, a repo-root-relative path (preserving a
// trailing "/" for a folder collection), to its content identifier in
// ref's tree, and adds a graph node for it (design D13: a folder path
// resolves to its tree id at a ref the same way `exo provenance show`
// does).
func resolveAtRef(root string, graph map[string]lib.Node, ref, path string) (string, error) {
	trailingSlash := strings.HasSuffix(path, "/")
	clean := filepath.ToSlash(filepath.Clean(strings.TrimSuffix(path, "/")))
	if clean == "." || clean == ".." || strings.HasPrefix(clean, "../") || filepath.IsAbs(clean) {
		return "", fmt.Errorf("%s:%s: path must be repository-relative", ref, path)
	}
	if trailingSlash {
		clean += "/"
	}
	reader := lib.NewRefReader(root, ref)
	id, err := reader.ResolveContentID(clean)
	if err != nil {
		return "", fmt.Errorf("resolve %s:%s: %w", ref, clean, err)
	}
	nodeType := "Entity"
	if strings.HasPrefix(id, lib.GitTreeURNPrefix) {
		nodeType = "Collection"
	}
	n := graph[id]
	if n == nil {
		n = lib.Node{"@id": id, "@type": nodeType}
	}
	n["exo:path"] = clean
	graph[id] = n
	return id, nil
}

// normalizeRepoPath resolves pathOrDir (as given on the command line,
// relative to the current working directory, or absolute) to a
// repo-root-relative path, preserving a trailing "/" for folder references.
// It rejects a path that resolves outside root.
//
// Only the containing directory's symlinks are resolved (via
// filepath.EvalSymlinks), never the final path component (the file or
// folder itself): $PWD, and a user-supplied absolute path, can go through a
// symlinked directory (a symlinked home or data directory is common on
// shared clusters), while `git rev-parse --show-toplevel` always returns
// the real path, so comparing them without resolving the directory
// component would misreport an in-repo path as outside the repository.
// Resolving the final component too would be wrong for a different reason:
// it would follow a git-annex symlink into .git/annex/objects.
func normalizeRepoPath(root, pathOrDir string) (string, error) {
	trailingSlash := strings.HasSuffix(pathOrDir, "/")
	clean := filepath.Clean(strings.TrimSuffix(pathOrDir, "/"))

	var joined string
	if filepath.IsAbs(clean) {
		joined = clean
	} else {
		cwd, err := os.Getwd()
		if err != nil {
			return "", fmt.Errorf("determine the current working directory: %w", err)
		}
		joined = filepath.Join(cwd, clean)
	}

	dir, base := filepath.Split(joined)
	realDir, err := filepath.EvalSymlinks(dir)
	if err != nil {
		return "", fmt.Errorf("resolve %s: %w", pathOrDir, err)
	}
	abs := filepath.Join(realDir, base)

	realRoot, err := filepath.EvalSymlinks(root)
	if err != nil {
		return "", fmt.Errorf("resolve the repository root: %w", err)
	}

	rel, err := filepath.Rel(realRoot, abs)
	if err != nil {
		return "", fmt.Errorf("resolve %s relative to the repository root: %w", pathOrDir, err)
	}
	rel = filepath.ToSlash(rel)
	if rel == "." || rel == ".." || strings.HasPrefix(rel, "../") {
		return "", fmt.Errorf("%s is outside the repository", pathOrDir)
	}
	if trailingSlash && !strings.HasSuffix(rel, "/") {
		rel += "/"
	}
	return rel, nil
}

// isUntrackedResolveError reports whether err from Reader.ResolveContentID
// means the path is untracked or does not exist in the checked state (as
// opposed to, for example, a usage error like a directory path missing its
// trailing "/"): the untracked/missing cases should always be reported with
// an "exo add" hint, including when git status prints nothing for the path
// because it is gitignored (spec scenario "Untracked input is rejected").
func isUntrackedResolveError(err error) bool {
	msg := err.Error()
	return strings.Contains(msg, "not tracked in the index") ||
		strings.Contains(msg, "not found") ||
		strings.Contains(msg, "not present at")
}

// checkWorktreeClean rejects an untracked path, or a path (file, or any
// file under a folder) whose worktree content differs from the index
// (design D6: "Untracked files, and files whose worktree content differs
// from the index, are rejected with a hint to run exo add first"). path
// must already be repo-root-relative. --literal-pathspecs stops pathspec
// magic characters ("*", "?", "[") in path from matching unrelated files,
// matching how Reader itself invokes git (see internal/provenance.state.go,
// !253).
func checkWorktreeClean(root, path string) error {
	arg := strings.TrimSuffix(path, "/")
	cmd := exec.Command("git", "--literal-pathspecs", "status", "--porcelain", "--untracked-files=all", "--", arg)
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("git status %s: %w", arg, err)
	}
	for _, line := range strings.Split(strings.TrimRight(string(out), "\n"), "\n") {
		if line == "" {
			continue
		}
		if len(line) < 2 || line[1] != ' ' {
			return fmt.Errorf("%s is untracked or its worktree content differs from the index; run \"exo add %s\" first", path, arg)
		}
	}
	return nil
}

func toValue(ids []string) any {
	if len(ids) == 1 {
		return ids[0]
	}
	out := make([]any, len(ids))
	for i, id := range ids {
		out[i] = id
	}
	return out
}

func graphNodes(graph map[string]lib.Node) []lib.Node {
	out := make([]lib.Node, 0, len(graph))
	for _, n := range graph {
		out = append(out, n)
	}
	return out
}

// recordSlug derives the record file name's slug (design D3) from the
// first --generated path, for example "data/result.csv" -> "result".
func recordSlug(path string) string {
	base := filepath.Base(strings.TrimSuffix(path, "/"))
	base = strings.TrimSuffix(base, filepath.Ext(base))
	slug := lib.Slugify(base)
	if slug == "" {
		slug = "record"
	}
	return slug
}

func repoRoot() (string, error) {
	out, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		return "", fmt.Errorf("not inside a git repository: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// writeRecordFile writes data to repo-root-relative path, failing if the
// file already exists: a record file is never overwritten (design D6).
func writeRecordFile(root, path string, data []byte) error {
	full := filepath.Join(root, path)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}
	f, err := os.OpenFile(full, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o644)
	if err != nil {
		return fmt.Errorf("create %s: %w", path, err)
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return fmt.Errorf("write %s: %w", path, err)
	}
	return f.Close()
}

// stageRecord stages path as a git blob regardless of annex.largefiles
// (design D15: "exo provenance add stages with git -c annex.largefiles=
// nothing add, like exo add does for protected paths").
func stageRecord(root, path string) error {
	cmd := exec.Command("git", "-c", "annex.largefiles=nothing", "add", path)
	cmd.Dir = root
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("stage %s: %w\n%s", path, err, out)
	}
	return nil
}
